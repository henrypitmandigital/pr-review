// Runs before any checkout: no repository or comment code executes. Reads
// structured event data only and fails closed on API errors or insufficient
// repository permission.

// The exact command, alone or followed by exactly the Claude Code attribution
// footer. PR-Agent ignores the footer words (none is a `--key=value` setting);
// any other trailing text could change PR-Agent settings, so it is rejected.
const FOOTER =
  /^\/review\n\n---\n_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code(?:\/session_[A-Za-z0-9]+)?\)_$/;

export function isReviewCommand(body) {
  if (typeof body !== "string") return false;
  const normalized = body.replace(/\r\n/g, "\n");
  return normalized === "/review" || FOOTER.test(normalized.trimEnd());
}

export async function authorize({
  context,
  github,
  core,
  acknowledge = false,
  runAttempt = process.env.GITHUB_RUN_ATTEMPT,
}) {
  const event = context.payload;
  const author = event?.comment?.user;
  if (
    context.eventName !== "issue_comment" ||
    event.action !== "created" ||
    !event.issue?.pull_request ||
    !isReviewCommand(event.comment?.body) ||
    author?.type !== "User" ||
    !Number.isSafeInteger(author?.id) ||
    author.id <= 0 ||
    // A rerun is never a new authorization to spend.
    Number(runAttempt) !== 1
  ) {
    core.setOutput("allowed", "false");
    return false;
  }
  let allowed;
  try {
    const { data } = await github.rest.repos.getCollaboratorPermissionLevel({
      ...context.repo,
      username: author.login,
    });
    // Bind the API principal to the original author, even after login renames.
    allowed =
      data.user?.id === author.id && ["write", "maintain", "admin"].includes(data.permission);
  } catch {
    core.setOutput("allowed", "false");
    core.setFailed("Cannot confirm the original commenter permission; no paid review.");
    return false;
  }
  core.setOutput("allowed", String(allowed));
  if (!allowed) {
    core.notice("PR-Agent requires repository write permission.");
    return false;
  }
  if (acknowledge) {
    try {
      await github.rest.reactions.createForIssueComment({
        ...context.repo,
        comment_id: event.comment.id,
        content: "eyes",
      });
    } catch {
      core.warning("Could not add the acknowledgement reaction.");
    }
  }
  return true;
}
